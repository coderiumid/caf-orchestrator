/**
 * The validation gate between implementation and review (CAF-SDD-04a): old
 * target repos run caf-qa and write qa-report.md; repos generated by the SDD
 * initiator run caf-validator and write validate-report.md. Both reports share
 * one Status: rule (readQaReport/readValidateReport), and both map onto the
 * same `qa` orchestration gate, config keys (agents.qa.maxRetries) and skip
 * directive (`- QA:`) — only the agent and file names differ.
 */
interface ValidationGate {
  agentName: 'caf-qa' | 'caf-validator';
  /** Short name used in PR bodies and skip notes. */
  label: string;
  /** The report this agent is asked to write. */
  reportFile: string;
}

const QA_GATE: ValidationGate = { agentName: 'caf-qa', label: 'QA', reportFile: 'qa-report.md' };
const VALIDATOR_GATE: ValidationGate = { agentName: 'caf-validator', label: 'Validator', reportFile: 'validate-report.md' };

/** A gate report plus the file it was actually read from (validate-report.md, or qa-report.md as fallback). */
interface ValidationResult {
  report: QaReport;
  reportFile: string;
}

function buildPrBody(
  job: ExistingJobPayload,
  docsNote: string,
  qaReport: QaReport,
  reviewerReport: ReviewerReport,
  qualityGateWarning: string,
  validation: { label: string; reportFile: string },
  acSummaryText = '',
): string {
  const lines: string[] = [];

  if (acSummaryText) {
    lines.push(acSummaryText, '');
  }

  if (qualityGateWarning) {
    lines.push(qualityGateWarning, '');
  }

  lines.push(
    `Ticket: ${job.ticketKey}`,
    job.ticketDescription || '',
    '',
    '## Reports',
    `- Requirements: \`.caf/tasks/${job.ticketKey}/requirements.md\``,
    `- Verify: \`.caf/tasks/${job.ticketKey}/verify-report.md\``,
    `- ${validation.label}: \`.caf/tasks/${job.ticketKey}/${validation.reportFile}\``,
    `- Review: \`.caf/tasks/${job.ticketKey}/review-notes.md\``,
    '',
    docsNote,
    '',
    qaReport.raw,
    '',
    reviewerReport.raw,
  );

  return lines.join('\n');
}

